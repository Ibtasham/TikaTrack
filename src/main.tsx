import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';

import App from './App';
import { ErrorBoundary } from './components/ErrorBoundary';
import { resolveSpaRedirect } from './lib/spaRedirect';
import './styles/index.css';

// Must run before React Router reads the URL: on hosts without rewrite rules
// (GitHub Pages) this turns the `404.html` bounce back into the intended route.
// It is a no-op everywhere else. See src/lib/spaRedirect.ts.
resolveSpaRedirect();

// Tier 1 Google Maps Platform quota & auth listener before map initialization.
if (typeof window !== 'undefined') {
  (window as Window & { gm_authFailure?: () => void }).gm_authFailure = () => {
    window.dispatchEvent(new CustomEvent('gmp-quota-exceeded'));
  };
  const origConsoleError = console.error;
  console.error = (...args: unknown[]) => {
    origConsoleError.apply(console, args);
    const msg = args.map((item) => String(item)).join(' ');
    if (msg.includes('OverQuotaMapError') || msg.includes('QuotaExceededError')) {
      window.dispatchEvent(new CustomEvent('gmp-quota-exceeded'));
    }
  };
}

const container = document.getElementById('root');
if (!container) {
  // index.html is generated by Vite from the repo's own template, so this can
  // only happen if someone serves the bundle into foreign markup.
  throw new Error('TikaTrack could not find the #root element to mount into.');
}

createRoot(container).render(
  <StrictMode>
    <ErrorBoundary>
      <App />
    </ErrorBoundary>
  </StrictMode>,
);
