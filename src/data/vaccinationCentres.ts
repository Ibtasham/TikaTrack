export const getCentresByDistrict = (district: string): VaccinationCentre[] => {
  return allVaccinationCentres.filter(centre => 
    centre.district.toLowerCase() === district.toLowerCase()
  );
};

export const getCentresByDivision = (division: string): VaccinationCentre[] => {
  return allVaccinationCentres.filter(centre => 
    centre.division.toLowerCase() === division.toLowerCase()
  );
};

export const searchCentres = (query: string): VaccinationCentre[] => {
  const lowerQuery = query.toLowerCase();
  return allVaccinationCentres.filter(centre =>
    centre.name.en.toLowerCase().includes(lowerQuery) ||
    centre.name.bn.includes(query) ||
    centre.address.en.toLowerCase().includes(lowerQuery) ||
    centre.address.bn.includes(query) ||
    centre.district.toLowerCase().includes(lowerQuery) ||
    centre.division.toLowerCase().includes(lowerQuery)
  );
};

